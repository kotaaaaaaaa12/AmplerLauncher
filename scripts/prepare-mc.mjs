#!/usr/bin/env node
// Runs automatically as Wrangler's custom build step ("build.command" in wrangler.jsonc),
// so it is part of `npx wrangler deploy` (including Workers Builds).
//
// 1. Finds files that are too big for Workers Static Assets (25 MiB) and lists them in
//    .assetsignore so Wrangler does not try to upload them as static assets.
// 2. Makes sure the R2 bucket exists, then uploads those large files to R2.
//    Files that have not changed since the last upload are skipped.
//
// src/worker.js serves the large files from R2 under the same URL path.
//
// Options:
//   --dry-run     Print the plan without writing .assetsignore or touching R2.
//   --no-upload   Only write .assetsignore.
//   --force       Upload every large file again, even if it is unchanged.

import { spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { createReadStream, existsSync } from "node:fs";
import { mkdtemp, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { contentTypeFor } from "../src/content-types.js";

const FALLBACK_BUCKET = "amplerlauncher-mc";
const BUCKET_BINDING = "MC_BUCKET";
const MAX_ASSET_SIZE = 25 * 1024 * 1024; // Workers Static Assets: 25 MiB per file
const MANIFEST_KEY = "_manifest/large-files.json";
const RETRIES = 2;

// Never scanned and never uploaded as assets (relative to the repository root).
const ROOT_SKIP = new Set([".git", ".github", ".wrangler", "node_modules", "src", "scripts"]);
const ALWAYS_SKIP = new Set([".git", "node_modules"]);
const IGNORED_NAMES = new Set([".DS_Store", "Thumbs.db"]);

// Patterns that are always written to .assetsignore (gitignore syntax).
const BASE_IGNORE = [
  "/src/",
  "/scripts/",
  "/node_modules/",
  "/.git/",
  "/.github/",
  "/.wrangler/",
  "/wrangler.jsonc",
  "/package.json",
  "/package-lock.json",
  "/CLOUDFLARE.md",
  "/README.md",
  "/.gitignore",
  "/.dev.vars",
  "/Eaglercraft-1.20.4-main.zip",
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = new Set(process.argv.slice(2));
const dryRun = args.has("--dry-run");
const force = args.has("--force");
const wranglerCommand = process.env.WRANGLER_COMMAND ?? "";
const skipUpload = args.has("--no-upload") || wranglerCommand === "dev" || wranglerCommand === "types";
const wranglerBin =
  process.env.WRANGLER_BIN ?? path.join(root, "node_modules", "wrangler", "bin", "wrangler.js");

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

async function readBucketName() {
  try {
    const text = await readFile(path.join(root, "wrangler.jsonc"), "utf8");
    const json = text
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/^\s*\/\/.*$/gm, "")
      .replace(/,(\s*[}\]])/g, "$1");
    const config = JSON.parse(json);
    const binding = (config.r2_buckets ?? []).find((b) => b.binding === BUCKET_BINDING);
    if (binding?.bucket_name) return binding.bucket_name;
  } catch {
    // Fall through to the default name.
  }
  return FALLBACK_BUCKET;
}

async function findLargeFiles(dir = root, relative = "") {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (IGNORED_NAMES.has(entry.name)) continue;
    if (entry.isDirectory()) {
      if (ALWAYS_SKIP.has(entry.name)) continue;
      if (relative === "" && ROOT_SKIP.has(entry.name)) continue;
      found.push(...(await findLargeFiles(path.join(dir, entry.name), `${relative}${entry.name}/`)));
    } else if (entry.isFile()) {
      const file = path.join(dir, entry.name);
      const { size } = await stat(file);
      if (size >= MAX_ASSET_SIZE) found.push({ file, key: relative + entry.name, size });
    }
  }
  return found;
}

// Escapes characters that are special in gitignore patterns.
function escapeIgnorePath(key) {
  return "/" + key.replace(/[\\*?[\]]/g, "\\$&");
}

async function writeAssetsIgnore(large) {
  const lines = [
    "# Generated by scripts/prepare-mc.mjs on every deploy. Do not edit by hand.",
    "# Files listed here are NOT uploaded as static assets.",
    ...BASE_IGNORE,
    "",
    "# Files of 25 MiB or more. They are stored in R2 and served by src/worker.js.",
    ...large.map((item) => escapeIgnorePath(item.key)),
    "",
  ];
  const content = lines.join("\n");
  const target = path.join(root, ".assetsignore");
  const current = existsSync(target) ? await readFile(target, "utf8") : null;
  if (current !== content) {
    await writeFile(target, content);
    console.log(".assetsignore updated.");
  } else {
    console.log(".assetsignore is up to date.");
  }
}

function sha256(file) {
  return new Promise((resolve, reject) => {
    const hash = createHash("sha256");
    createReadStream(file)
      .on("data", (chunk) => hash.update(chunk))
      .on("error", reject)
      .on("end", () => resolve(hash.digest("hex")));
  });
}

function wrangler(wranglerArgs) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [wranglerBin, ...wranglerArgs], {
      stdio: ["ignore", "pipe", "pipe"],
    });
    let output = "";
    child.stdout.on("data", (chunk) => (output += chunk));
    child.stderr.on("data", (chunk) => (output += chunk));
    child.on("error", reject);
    child.on("close", (code) => resolve({ code, output: output.trim() }));
  });
}

async function putObject(bucket, key, file) {
  const putArgs = [
    "r2", "object", "put", `${bucket}/${key}`,
    "--file", file,
    "--content-type", contentTypeFor(key),
    "--remote",
  ];
  for (let attempt = 0; ; attempt++) {
    const result = await wrangler(putArgs);
    if (result.code === 0) return;
    if (attempt >= RETRIES) {
      throw new Error(`Upload failed for ${key}\n${result.output}`);
    }
  }
}

async function ensureBucket(bucket) {
  if ((await wrangler(["r2", "bucket", "info", bucket])).code === 0) {
    console.log(`R2 bucket "${bucket}" exists.`);
    return;
  }
  console.log(`Creating R2 bucket "${bucket}"...`);
  const created = await wrangler(["r2", "bucket", "create", bucket]);
  if (created.code !== 0) {
    throw new Error(`Could not create R2 bucket "${bucket}"\n${created.output}`);
  }
}

async function syncToR2(bucket, large) {
  await ensureBucket(bucket);
  if (large.length === 0) return;

  const tmp = await mkdtemp(path.join(os.tmpdir(), "ampler-"));
  const manifestFile = path.join(tmp, "manifest.json");
  try {
    let manifest = {};
    const fetched = await wrangler([
      "r2", "object", "get", `${bucket}/${MANIFEST_KEY}`, "--file", manifestFile, "--remote",
    ]);
    if (fetched.code === 0) {
      try {
        manifest = JSON.parse(await readFile(manifestFile, "utf8"));
      } catch {
        manifest = {};
      }
    }

    let changed = false;
    try {
      for (const item of large) {
        const hash = await sha256(item.file);
        const known = manifest[item.key];
        if (!force && known && known.sha256 === hash && known.size === item.size) {
          console.log(`unchanged  ${item.key}`);
          continue;
        }
        console.log(`uploading  ${item.key} (${(item.size / 1024 / 1024).toFixed(1)} MiB)`);
        await putObject(bucket, item.key, item.file);
        manifest[item.key] = { sha256: hash, size: item.size };
        changed = true;
      }
    } finally {
      // Save progress even if a later upload failed.
      if (changed) {
        await writeFile(manifestFile, JSON.stringify(manifest, null, 2));
        await putObject(bucket, MANIFEST_KEY, manifestFile);
      }
    }
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const bucket = await readBucketName();
  const large = (await findLargeFiles()).sort((a, b) => a.key.localeCompare(b.key));
  console.log(`Found ${large.length} file(s) of 25 MiB or more.`);
  for (const item of large) {
    console.log(`  ${item.key} (${(item.size / 1024 / 1024).toFixed(1)} MiB)`);
  }

  if (dryRun) {
    console.log(`Dry run: would write .assetsignore and sync to R2 bucket "${bucket}".`);
    return;
  }

  await writeAssetsIgnore(large);

  if (skipUpload) {
    console.log("Skipping R2 upload.");
    return;
  }
  if (!existsSync(wranglerBin)) {
    throw new Error("Wrangler is not installed. Run `npm install` first.");
  }
  await syncToR2(bucket, large);
  console.log("R2 sync finished.");
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
